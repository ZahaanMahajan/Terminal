/**
 * compiler/emit.ts — Phase 4, step 2: IR → idiomatic dotfile text.
 *
 * Pure and **deterministic**: the same IR always produces the same bytes (no timestamps, no map
 * iteration order). Determinism is what makes the golden tests meaningful and diffs informative.
 *
 * Quoting matters and differs by intent:
 *   - `export` values are double-quoted (and `"` / `\` escaped) so `$VAR` still expands —
 *     `export PATH="$HOME/bin:$PATH"` must keep expanding.
 *   - `alias` values are single-quoted (with the `'\''` trick for embedded quotes) so the alias
 *     body is stored verbatim and expands when *invoked*, not when defined.
 */

import type { ShellKind } from './ast';
import type { ShellIR, ShellStmt, StarshipIR } from './ir';

/** Double-quote for export values: escape `\` and `"`, keep `$` for expansion. */
function doubleQuote(value: string): string {
  return '"' + value.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

/** Single-quote for alias values: close-escape-reopen for embedded single quotes. */
function singleQuote(value: string): string {
  return "'" + value.replace(/'/g, "'\\''") + "'";
}

function emitStmt(stmt: ShellStmt, shell: ShellKind): string {
  switch (stmt.kind) {
    case 'comment':
      return `# ${stmt.text}`;
    case 'blank':
      return '';
    case 'export':
      return `export ${stmt.name}=${doubleQuote(stmt.value)}`;
    case 'alias':
      return `alias ${stmt.name}=${singleQuote(stmt.value)}`;
    case 'option':
      return shell === 'zsh' ? `setopt ${stmt.name}` : `shopt -s ${stmt.name}`;
    case 'plugin': {
      const ext = shell === 'zsh' ? 'zsh' : 'bash';
      const path = `"$HOME/.${shell}/plugins/${stmt.id}/${stmt.id}.${ext}"`;
      return `[ -f ${path} ] && source ${path}`;
    }
    case 'initPrompt':
      return `eval "$(starship init ${shell})"`;
  }
}

export function emitShell(ir: ShellIR): string {
  return ir.statements.map((s) => emitStmt(s, ir.shell)).join('\n') + '\n';
}

function tomlValue(v: string | boolean): string {
  return typeof v === 'boolean' ? String(v) : `"${v}"`;
}

export function emitStarship(ir: StarshipIR): string {
  const lines = ['# Generated by Termi. Edit the setup, not this file.', ''];
  for (const s of ir.settings) lines.push(`${s.key} = ${tomlValue(s.value)}`);
  lines.push(`format = "${ir.format}"`);
  return lines.join('\n') + '\n';
}
